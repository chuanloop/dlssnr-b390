// Generated by windows/build/build_optiscaler_nr.sh; every Vulkan entry point in the two
// translation units is a tail jump through this table, filled by nr_vk_load().
extern "C" void nr_vk_load(void);

namespace {

void fail(const char* what) {
    std::fprintf(stderr, "harness: %s\n", what);
    std::exit(1);
}
void check(VkResult r, const char* what) {
    if (r != VK_SUCCESS) {
        std::fprintf(stderr, "harness: %s failed (%d)\n", what, int(r));
        std::exit(1);
    }
}

#define VKFN(name) PFN_##name name = nullptr

struct Api {
    PFN_vkGetInstanceProcAddr gipa{};
    VKFN(vkCreateInstance); VKFN(vkEnumeratePhysicalDevices); VKFN(vkGetPhysicalDeviceProperties);
    VKFN(vkGetPhysicalDeviceFeatures2); VKFN(vkGetPhysicalDeviceQueueFamilyProperties);
    VKFN(vkCreateDevice); VKFN(vkGetDeviceQueue); VKFN(vkCreateCommandPool);
    VKFN(vkAllocateCommandBuffers); VKFN(vkBeginCommandBuffer); VKFN(vkEndCommandBuffer);
    VKFN(vkQueueSubmit); VKFN(vkQueueWaitIdle); VKFN(vkCreateImage);
    VKFN(vkGetImageMemoryRequirements); VKFN(vkGetPhysicalDeviceMemoryProperties);
    VKFN(vkAllocateMemory); VKFN(vkBindImageMemory); VKFN(vkCreateImageView);
    VKFN(vkCreateBuffer); VKFN(vkGetBufferMemoryRequirements); VKFN(vkBindBufferMemory);
    VKFN(vkMapMemory); VKFN(vkUnmapMemory); VKFN(vkCmdCopyBufferToImage);
    VKFN(vkCmdCopyImageToBuffer); VKFN(vkCreateFence); VKFN(vkWaitForFences);
    VKFN(vkCmdPipelineBarrier);
};

Api api;

void load_api(VkInstance instance) {
    // LoadLibraryA, not GetModuleHandleA: this process has no static import of vulkan-1.dll, so
    // the module is only present if something already loaded it.
    HMODULE loader = LoadLibraryA("vulkan-1.dll");
    if (!loader) fail("vulkan-1.dll is not installed");
    api.gipa = reinterpret_cast<PFN_vkGetInstanceProcAddr>(
        GetProcAddress(loader, "vkGetInstanceProcAddr"));
    if (!api.gipa) fail("vulkan-1.dll has no vkGetInstanceProcAddr");
// Some loaders return NULL for the *global* commands (vkCreateInstance among them) when the
// query carries a non-NULL instance, even though the spec allows them to be asked that way.
// Try the instance first (that is what device-level commands need) and fall back to the global
// query before giving up.
#define LOAD(name) \
    api.name = reinterpret_cast<PFN_##name>(api.gipa(instance, #name)); \
    if (!api.name) api.name = reinterpret_cast<PFN_##name>(api.gipa(VK_NULL_HANDLE, #name)); \
    if (!api.name) fail("missing " #name)
    LOAD(vkCreateInstance); LOAD(vkEnumeratePhysicalDevices); LOAD(vkGetPhysicalDeviceProperties);
    LOAD(vkGetPhysicalDeviceFeatures2); LOAD(vkGetPhysicalDeviceQueueFamilyProperties);
    LOAD(vkCreateDevice); LOAD(vkGetDeviceQueue); LOAD(vkCreateCommandPool);
    LOAD(vkAllocateCommandBuffers); LOAD(vkBeginCommandBuffer); LOAD(vkEndCommandBuffer);
    LOAD(vkQueueSubmit); LOAD(vkQueueWaitIdle); LOAD(vkCreateImage);
    LOAD(vkGetImageMemoryRequirements); LOAD(vkGetPhysicalDeviceMemoryProperties);
    LOAD(vkAllocateMemory); LOAD(vkBindImageMemory); LOAD(vkCreateImageView);
    LOAD(vkCreateBuffer); LOAD(vkGetBufferMemoryRequirements); LOAD(vkBindBufferMemory);
    LOAD(vkMapMemory); LOAD(vkUnmapMemory); LOAD(vkCmdCopyBufferToImage);
    LOAD(vkCmdCopyImageToBuffer); LOAD(vkCreateFence); LOAD(vkWaitForFences);
    LOAD(vkCmdPipelineBarrier);
#undef LOAD
}

struct Image {
    VkImage image{};
    VkDeviceMemory memory{};
    VkImageView view{};
    VkFormat format{};
    uint32_t width{}, height{};
};

uint32_t pick_memory(VkPhysicalDevice phy, uint32_t bits, VkMemoryPropertyFlags want) {
    VkPhysicalDeviceMemoryProperties mp{};
    api.vkGetPhysicalDeviceMemoryProperties(phy, &mp);
    for (uint32_t i = 0; i < mp.memoryTypeCount; ++i)
        if ((bits & (1u << i)) && (mp.memoryTypes[i].propertyFlags & want) == want) return i;
    fail("no memory type for the request");
    return 0;
}

Image make_image(VkPhysicalDevice phy, VkDevice dev, VkFormat fmt, uint32_t w, uint32_t h,
                 VkImageUsageFlags usage) {
    Image out{};
    out.format = fmt;
    out.width = w;
    out.height = h;
    VkImageCreateInfo ci{VK_STRUCTURE_TYPE_IMAGE_CREATE_INFO};
    ci.imageType = VK_IMAGE_TYPE_2D;
    ci.format = fmt;
    ci.extent = {w, h, 1};
    ci.mipLevels = 1;
    ci.arrayLayers = 1;
    ci.samples = VK_SAMPLE_COUNT_1_BIT;
    ci.tiling = VK_IMAGE_TILING_OPTIMAL;
    ci.usage = usage;
    ci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
    ci.initialLayout = VK_IMAGE_LAYOUT_UNDEFINED;
    check(api.vkCreateImage(dev, &ci, nullptr, &out.image), "vkCreateImage");
    VkMemoryRequirements req{};
    api.vkGetImageMemoryRequirements(dev, out.image, &req);
    VkMemoryAllocateInfo ai{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
    ai.allocationSize = req.size;
    ai.memoryTypeIndex = pick_memory(phy, req.memoryTypeBits, VK_MEMORY_PROPERTY_DEVICE_LOCAL_BIT);
    check(api.vkAllocateMemory(dev, &ai, nullptr, &out.memory), "vkAllocateMemory(image)");
    check(api.vkBindImageMemory(dev, out.image, out.memory, 0), "vkBindImageMemory");
    VkImageViewCreateInfo vi{VK_STRUCTURE_TYPE_IMAGE_VIEW_CREATE_INFO};
    vi.image = out.image;
    vi.viewType = VK_IMAGE_VIEW_TYPE_2D;
    vi.format = fmt;
    vi.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
    check(api.vkCreateImageView(dev, &vi, nullptr, &out.view), "vkCreateImageView");
    return out;
}

void layout(VkCommandBuffer cb, VkImage image, VkImageLayout from, VkImageLayout to,
            VkPipelineStageFlags src, VkAccessFlags src_access, VkPipelineStageFlags dst,
            VkAccessFlags dst_access) {
    VkImageMemoryBarrier b{VK_STRUCTURE_TYPE_IMAGE_MEMORY_BARRIER};
    b.srcAccessMask = src_access;
    b.dstAccessMask = dst_access;
    b.oldLayout = from;
    b.newLayout = to;
    b.srcQueueFamilyIndex = b.dstQueueFamilyIndex = VK_QUEUE_FAMILY_IGNORED;
    b.image = image;
    b.subresourceRange = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 1, 0, 1};
    api.vkCmdPipelineBarrier(cb, src, dst, 0, 0, nullptr, 0, nullptr, 1, &b);
}

}  // namespace

int main(int argc, char** argv) {
    std::string manifest, input, out_dir;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--manifest" && i + 1 < argc) manifest = argv[++i];
        else if (a == "--input" && i + 1 < argc) input = argv[++i];
        else if (a == "--out" && i + 1 < argc) out_dir = argv[++i];
    }
    if (manifest.empty() || input.empty() || out_dir.empty()) {
        std::fprintf(stderr, "usage: seam_harness --manifest DIR --input FILE --out DIR\n");
        return 2;
    }
    if (!std::filesystem::create_directory(out_dir)) fail("--out must be a fresh directory");
    // --manifest is the *root* the host would pass as RuntimeConfig::root, not the manifest
    // directory itself: the seam resolves `dlssnr-b390/manifest`, then `manifest`, then root,
    // exactly as nr_runtime.cpp:1159 resolves `dlssnr-b390`. Accept the same three.
    {
        const std::filesystem::path root(manifest);
        bool found = false;
        for (const auto& candidate :
             {root / "dlssnr-b390" / "manifest", root / "manifest", root})
            if (std::filesystem::is_regular_file(candidate / "port_network_manifest.json")) found = true;
        if (!found) fail("--manifest must be a root the seam can find port_network_manifest.json under");
    }

    // The DLL's Vulkan entry points are lazy; the host that normally calls this is the NGX core.
    nr_vk_load();

    VkApplicationInfo app{VK_STRUCTURE_TYPE_APPLICATION_INFO};
    app.pApplicationName = "seam_harness";
    app.apiVersion = VK_API_VERSION_1_3;
    VkInstanceCreateInfo ici{VK_STRUCTURE_TYPE_INSTANCE_CREATE_INFO};
    ici.pApplicationInfo = &app;
    VkInstance instance{};
    {
        auto create = reinterpret_cast<PFN_vkCreateInstance>(
            GetProcAddress(LoadLibraryA("vulkan-1.dll"), "vkCreateInstance"));
        if (!create) fail("no vkCreateInstance");
        check(create(&ici, nullptr, &instance), "vkCreateInstance");
    }
    load_api(instance);

    uint32_t count = 0;
    check(api.vkEnumeratePhysicalDevices(instance, &count, nullptr), "vkEnumeratePhysicalDevices");
    if (!count) fail("no Vulkan device");
    std::vector<VkPhysicalDevice> phys(count);
    check(api.vkEnumeratePhysicalDevices(instance, &count, phys.data()), "vkEnumeratePhysicalDevices");
    // Same selection as the runner: Intel, and the two device ids the FP16 coopmat path is
    // verified on. Picking device 0 blindly would sometimes land on a software device.
    VkPhysicalDevice phy = VK_NULL_HANDLE;
    VkPhysicalDeviceProperties props{};
    for (VkPhysicalDevice candidate : phys) {
        VkPhysicalDeviceProperties p{};
        api.vkGetPhysicalDeviceProperties(candidate, &p);
        if (p.vendorID == 0x8086 && (p.deviceID == 0xe20b || p.deviceID == 0xb080)) {
            phy = candidate;
            props = p;
        }
    }
    if (!phy) fail("Intel Arc B580/B390 missing");
    std::printf("harness: device %s\n", props.deviceName);

    float priority = 1.0f;
    VkDeviceQueueCreateInfo qci{VK_STRUCTURE_TYPE_DEVICE_QUEUE_CREATE_INFO};
    qci.queueFamilyIndex = 0;
    qci.queueCount = 1;
    qci.pQueuePriorities = &priority;

    // The same feature set port_network_model_runner.cpp enables (line 270 onwards), because that
    // is the contract nrvk_backend_init checks for. A device without them fails at init with -3,
    // which the seam logs -- so ask for exactly these and let it say so.
    VkPhysicalDeviceCooperativeMatrixFeaturesKHR cm{
        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_COOPERATIVE_MATRIX_FEATURES_KHR};
    VkPhysicalDeviceShaderFloat16Int8Features half{
        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SHADER_FLOAT16_INT8_FEATURES};
    VkPhysicalDevice16BitStorageFeatures storage{
        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_16BIT_STORAGE_FEATURES};
    VkPhysicalDeviceSubgroupSizeControlFeatures subgroup{
        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SUBGROUP_SIZE_CONTROL_FEATURES};
    VkPhysicalDeviceSynchronization2Features sync{
        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_SYNCHRONIZATION_2_FEATURES};
    VkPhysicalDeviceVulkanMemoryModelFeatures model{
        VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_MEMORY_MODEL_FEATURES};
    VkPhysicalDeviceFeatures2 f2{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2};
    f2.pNext = &cm;
    cm.pNext = &half;
    half.pNext = &storage;
    storage.pNext = &subgroup;
    subgroup.pNext = &sync;
    sync.pNext = &model;
    api.vkGetPhysicalDeviceFeatures2(phy, &f2);
    if (!cm.cooperativeMatrix || !half.shaderFloat16 || !storage.storageBuffer16BitAccess ||
        !subgroup.subgroupSizeControl || !subgroup.computeFullSubgroups || !sync.synchronization2 ||
        !model.vulkanMemoryModel)
        fail("device lacks the FP16/coop/subgroup/synchronization2/VulkanMemoryModel set");
    model.vulkanMemoryModelDeviceScope = VK_FALSE;
    model.vulkanMemoryModelAvailabilityVisibilityChains = VK_FALSE;
    cm.cooperativeMatrixRobustBufferAccess = VK_FALSE;
    half.shaderInt8 = VK_FALSE;
    storage.uniformAndStorageBuffer16BitAccess = VK_FALSE;
    storage.storagePushConstant16 = VK_FALSE;
    storage.storageInputOutput16 = VK_FALSE;

    uint32_t nq = 0;
    api.vkGetPhysicalDeviceQueueFamilyProperties(phy, &nq, nullptr);
    std::vector<VkQueueFamilyProperties> qprops(nq);
    api.vkGetPhysicalDeviceQueueFamilyProperties(phy, &nq, qprops.data());
    uint32_t family = 0;
    while (family < nq && !(qprops[family].queueFlags & VK_QUEUE_COMPUTE_BIT)) ++family;
    if (family == nq) fail("no compute queue family");
    qci.queueFamilyIndex = family;

    const char* ext = "VK_KHR_cooperative_matrix";
    VkDeviceCreateInfo dci{VK_STRUCTURE_TYPE_DEVICE_CREATE_INFO};
    dci.pNext = &f2;
    dci.queueCreateInfoCount = 1;
    dci.pQueueCreateInfos = &qci;
    dci.enabledExtensionCount = 1;
    dci.ppEnabledExtensionNames = &ext;
    VkDevice device{};
    check(api.vkCreateDevice(phy, &dci, nullptr, &device), "vkCreateDevice");
    VkQueue queue{};
    api.vkGetDeviceQueue(device, family, 0, &queue);

    const uint32_t W = 1280, H = 720;
    const VkFormat colour_format = VK_FORMAT_R32G32B32A32_SFLOAT;
    Image colour = make_image(phy, device, colour_format, W, H,
                              VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_STORAGE_BIT |
                              VK_IMAGE_USAGE_TRANSFER_SRC_BIT | VK_IMAGE_USAGE_TRANSFER_DST_BIT);

    // staging buffer: the runner's input is planar RGBA f32, the network's io plane is interleaved
    // (port_network_model_runner.cpp:447 does the same conversion when it feeds the plan).
    const size_t pixels = size_t(W) * size_t(H);
    std::vector<float> planar(pixels * 4);
    {
        std::ifstream in(input, std::ios::binary);
        if (!in) fail("cannot read --input");
        in.read(reinterpret_cast<char*>(planar.data()), std::streamsize(planar.size() * sizeof(float)));
        if (size_t(in.gcount()) != planar.size() * sizeof(float))
            fail("--input is not 4 planes of f32 at 1280x720");
    }
    std::vector<float> interleaved(pixels * 4);
    for (size_t y = 0; y < H; ++y)
        for (size_t x = 0; x < W; ++x) {
            float* o = interleaved.data() + (y * W + x) * 4;
            for (int c = 0; c < 4; ++c) o[c] = planar[c * pixels + y * W + x];
        }

    VkBuffer staging{};
    VkDeviceMemory staging_memory{};
    {
        VkBufferCreateInfo bci{VK_STRUCTURE_TYPE_BUFFER_CREATE_INFO};
        bci.size = interleaved.size() * sizeof(float);
        bci.usage = VK_BUFFER_USAGE_TRANSFER_SRC_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT;
        bci.sharingMode = VK_SHARING_MODE_EXCLUSIVE;
        check(api.vkCreateBuffer(device, &bci, nullptr, &staging), "vkCreateBuffer");
        VkMemoryRequirements req{};
        api.vkGetBufferMemoryRequirements(device, staging, &req);
        VkMemoryAllocateInfo ai{VK_STRUCTURE_TYPE_MEMORY_ALLOCATE_INFO};
        ai.allocationSize = req.size;
        ai.memoryTypeIndex = pick_memory(phy, req.memoryTypeBits,
                                         VK_MEMORY_PROPERTY_HOST_VISIBLE_BIT |
                                         VK_MEMORY_PROPERTY_HOST_COHERENT_BIT);
        check(api.vkAllocateMemory(device, &ai, nullptr, &staging_memory), "vkAllocateMemory(buffer)");
        check(api.vkBindBufferMemory(device, staging, staging_memory, 0), "vkBindBufferMemory");
        void* mapped = nullptr;
        check(api.vkMapMemory(device, staging_memory, 0, VK_WHOLE_SIZE, 0, &mapped), "vkMapMemory");
        std::memcpy(mapped, interleaved.data(), interleaved.size() * sizeof(float));
        api.vkUnmapMemory(device, staging_memory);
    }

    VkCommandPoolCreateInfo pci{VK_STRUCTURE_TYPE_COMMAND_POOL_CREATE_INFO};
    pci.flags = VK_COMMAND_POOL_CREATE_RESET_COMMAND_BUFFER_BIT;
    pci.queueFamilyIndex = family;
    VkCommandPool pool{};
    check(api.vkCreateCommandPool(device, &pci, nullptr, &pool), "vkCreateCommandPool");
    VkCommandBufferAllocateInfo cbi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_ALLOCATE_INFO};
    cbi.commandPool = pool;
    cbi.level = VK_COMMAND_BUFFER_LEVEL_PRIMARY;
    cbi.commandBufferCount = 1;
    VkCommandBuffer cmd{};
    check(api.vkAllocateCommandBuffers(device, &cbi, &cmd), "vkAllocateCommandBuffers");

    VkCommandBufferBeginInfo bi{VK_STRUCTURE_TYPE_COMMAND_BUFFER_BEGIN_INFO};
    check(api.vkBeginCommandBuffer(cmd, &bi), "vkBeginCommandBuffer");

    // upload
    layout(cmd, colour.image, VK_IMAGE_LAYOUT_UNDEFINED, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL,
           VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT, 0, VK_PIPELINE_STAGE_TRANSFER_BIT,
           VK_ACCESS_TRANSFER_WRITE_BIT);
    VkBufferImageCopy region{};
    region.imageSubresource = {VK_IMAGE_ASPECT_COLOR_BIT, 0, 0, 1};
    region.imageExtent = {W, H, 1};
    api.vkCmdCopyBufferToImage(cmd, staging, colour.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, 1,
                               &region);
    layout(cmd, colour.image, VK_IMAGE_LAYOUT_TRANSFER_DST_OPTIMAL, VK_IMAGE_LAYOUT_GENERAL,
           VK_PIPELINE_STAGE_TRANSFER_BIT, VK_ACCESS_TRANSFER_WRITE_BIT,
           VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT,
           VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_SHADER_WRITE_BIT);

    // --- the seam, handed what nr_pe_session would hand it --------------------------------------
    nr::HostDevice host{};
    host.instance = instance;
    host.physical = phy;
    host.device = device;
    host.queue = queue;
    host.queue_family = family;

    nr::RuntimeConfig cfg{};
    cfg.root = manifest;
    cfg.width = W;
    cfg.height = H;
    cfg.colour_format = colour_format;

    nr::Runtime runtime(host, cfg);

    nr::ColourFrame frame{};
    frame.image = colour.image;
    frame.format = colour_format;
    frame.width = W;
    frame.height = H;
    frame.before = VK_IMAGE_LAYOUT_GENERAL;
    frame.after = VK_IMAGE_LAYOUT_GENERAL;
    frame.usage = VK_IMAGE_USAGE_SAMPLED_BIT | VK_IMAGE_USAGE_STORAGE_BIT;

    nr::Controls controls{};   // AMD defaults: style 0, tone 1, structure 1, skin -1, mask on
    const nr::RecordResult result = runtime.record(cmd, frame, controls, true);
    std::printf("harness: record -> dispatches=%u applied=%d\n", result.network_dispatches,
                result.applied ? 1 : 0);

    layout(cmd, colour.image, VK_IMAGE_LAYOUT_GENERAL, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL,
           VK_PIPELINE_STAGE_COMPUTE_SHADER_BIT,
           VK_ACCESS_SHADER_READ_BIT | VK_ACCESS_SHADER_WRITE_BIT, VK_PIPELINE_STAGE_TRANSFER_BIT,
           VK_ACCESS_TRANSFER_READ_BIT);
    api.vkCmdCopyImageToBuffer(cmd, colour.image, VK_IMAGE_LAYOUT_TRANSFER_SRC_OPTIMAL, staging, 1,
                               &region);
    check(api.vkEndCommandBuffer(cmd), "vkEndCommandBuffer");

    VkFenceCreateInfo fci{VK_STRUCTURE_TYPE_FENCE_CREATE_INFO};
    VkFence fence{};
    check(api.vkCreateFence(device, &fci, nullptr, &fence), "vkCreateFence");
    VkSubmitInfo si{VK_STRUCTURE_TYPE_SUBMIT_INFO};
    si.commandBufferCount = 1;
    si.pCommandBuffers = &cmd;
    check(api.vkQueueSubmit(queue, 1, &si, fence), "vkQueueSubmit");
    check(api.vkWaitForFences(device, 1, &fence, VK_TRUE, UINT64_MAX), "vkWaitForFences");

    {
        void* mapped = nullptr;
        check(api.vkMapMemory(device, staging_memory, 0, VK_WHOLE_SIZE, 0, &mapped), "vkMapMemory");
        std::ofstream out(out_dir + "/frame.bin", std::ios::binary);
        out.write(static_cast<const char*>(mapped), std::streamsize(pixels * 4 * sizeof(float)));
        api.vkUnmapMemory(device, staging_memory);
    }
    std::printf("harness: wrote %s/frame.bin\n", out_dir.c_str());
    return 0;
}
