// R2 judgement: does the Runtime seam produce the same frame as the offline runner?
//
// `port_network_model_runner` drives the plan directly; the seam (`nr_runtime_our.cpp`) drives
// nrvk_backend_*, which gathers the frame onto the network grid through a shader. The gather is
// written to be the identity mapping when the render extent equals the grid
// (`port_network_bridge_gather.comp`, "active==source and rect==grid lands on exact texel
// centres"), so at 1280x720 the two paths must agree *bit for bit* -- not merely in PSNR. This
// harness is what decides that.
//
// It stands in for OptiScaler: it owns the device, the images and the command buffer, and the
// seam is handed exactly what nr_pe_session would hand it.
//
//   seam_harness --manifest local/vk102/manifest --input local/m0/in_720.f32 --out DIR
//
// DIR must not exist. Writes frame.bin (interleaved RGBA f32, the runner's own layout) so the
// two can be compared byte for byte with `sha256sum`.
#include "nr_runtime.hpp"

#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <string>
#include <vector>

#ifndef WIN32_LEAN_AND_MEAN
#define WIN32_LEAN_AND_MEAN
#endif
