"""Pin the backend's compile-time idea of the frame to whatever the runtime plan is.

Why this exists
---------------
`port_network_bridge_backend.cpp` used to spell 1280x720 as a literal in twelve places:
the supported-output check, the active-rect clamp, the motion-scale normalisation, the
history gate, the two gather/scatter push blocks and the gather dispatch count. Those
numbers are not the contract -- the *plan* is. A plan generated for 960x540 carries its
own frame size in `ioport_block70_2` (verified by disassembly: p0.zw splits the invocation
id, p5.xy is the motion-uv denominator), so the code has to follow the plan instead of
contradicting it.

This script writes the two things the C++ side cannot know on its own:

  generated/port_network_bridge_backend_frame.inc
      kFrameW, kFrameH and the two ioport float offsets, all derived from the plan.

  generated/port_network_bridge_backend_frozen.inc   (runtime hash line only)
      re-pinned to the plan actually on disk, so `checked_plan` accepts a plan that was
      regenerated by tools/gen_plan.py. Every other line of that file is left alone --
      cold-asset and shader hashes still have to match exactly.

Usage
-----
    python tools/freeze_plan.py                     # adopt whatever is on disk
    python tools/freeze_plan.py --plan local/vk102/manifest/plan-960x540.txt \\
        --install                                    # install it as the runtime plan

The plan's size is read from the plan itself, never from the command line, so the two
cannot disagree: `verify()` in gen_plan.py already refuses to emit a plan whose port
constants do not match its dispatch, and this script re-checks that here.
"""
import argparse
import importlib.util
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "local/vk102"
MANIFEST = MODEL / "manifest"
RUNTIME = MANIFEST / "port_network_runtime.txt"
GENERATED = MODEL / "generated"
FRAME_INC = GENERATED / "port_network_bridge_backend_frame.inc"
FROZEN_INC = GENERATED / "port_network_bridge_backend_frozen.inc"


def load_gen_plan():
    spec = importlib.util.spec_from_file_location("gen_plan", ROOT / "tools/gen_plan.py")
    module = importlib.util.module_from_spec(spec)
    sys.modules["gen_plan"] = module
    spec.loader.exec_module(module)
    return module


def port_frame(text):
    """Read (width, height) out of the output port's push block."""
    return frame_of(text)


def rehash(frozen_text, runtime_path):
    """Replace only the runtime hash; leave the cold/spv allow-list untouched."""
    lines = frozen_text.splitlines()
    replaced = 0
    for i, line in enumerate(lines):
        if line.startswith('static constexpr const char* frozen_runtime_sha='):
            lines[i] = f'static constexpr const char* frozen_runtime_sha="{sha(runtime_path)}";'
            replaced += 1
    if replaced != 1:
        raise SystemExit(f"expected exactly one frozen_runtime_sha line, found {replaced}")
    return "\n".join(lines) + "\n"


def sha(path):
    import hashlib

    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


LADDER_INC = GENERATED / "port_network_bridge_backend_ladder.inc"


def frame_of(text):
    """(frame_w, frame_h) out of the output port's push block.

    The port's block number is a property of the profile, not of the contract: the full
    layout calls it `ioport_block70_2`, the small profile `r75_ioport_block30_2`. Both
    resolve through `gen_plan.port_key`, so this reads either plan the same way.
    """
    gp = load_gen_plan()
    words = gp.FRAME_DIM_WORDS["ioport_block70_2"]
    current = None
    for line in text.splitlines():
        if line.startswith("PASS "):
            current = gp.port_key(line.split()[2].strip('"'))
        elif line.startswith("PUSH ") and current == "ioport_block70_2":
            push = [int(x) for x in line.split()[1:]]
            return push[words[0]], push[words[1]]
    raise SystemExit("no PUSH block for ioport_block70_2 -- not a PORT_NETWORK_1 plan?")


def canvas_of(text):
    """(canvas_w, canvas_h): the first pass carries the dispatch extent in push words 16/17."""
    for line in text.splitlines():
        if line.startswith("PUSH "):
            w = line.split()
            if len(w) > 18:
                return int(w[17]), int(w[18])
            break
    raise SystemExit("plan has no push block")


def write_ladder(manifest):
    """Emit the runtime plan table: every scale the backend may switch to, with its hash.

    The backend can switch scale without reallocating anything (BUFFER and BIND lines are
    identical across scales - measured), so what it needs is not a new build but a table of
    "which file, which hash, which extent". That is this file.
    """
    ladder = manifest / "ladder"
    entries = []
    for path in sorted(ladder.glob("plan-s*.txt")):
        text = path.read_text(encoding="utf-8")
        try:
            scale = float(path.stem.split("-")[1].lstrip("s"))
        except (IndexError, ValueError):
            continue
        fw, fh = frame_of(text)
        cw, ch = canvas_of(text)
        entries.append((scale, fw, fh, cw, ch, path.name, sha(path)))
    # A profile without a ladder still has to compile: the table is empty and every consumer
    # is written as `for (... <kLadderCount)` with a `best<kLadderCount` guard, so zero
    # entries means "this build cannot switch scale" rather than a missing header.
    lines = ["// Generated by tools/freeze_plan.py -- do not edit.",
             "// Which plan each working scale loads, and the hash that makes it the right one.",
             "struct LadderPlan { double scale; uint32_t frame_w,frame_h,canvas_w,canvas_h; const char* path; const char* sha; };",
             "static constexpr LadderPlan ladder_plans[]={"]
    if not entries:
        # Zero-length arrays are not standard C++; one inert row keeps the table well-formed
        # while kLadderCount=0 stops every loop before it reads it.
        lines.append('{0.0f,0u,0u,0u,0u,"",""},')
    for scale, fw, fh, cw, ch, name, digest in entries:
        lines.append(f'{{{scale:.2f}f,{fw}u,{fh}u,{cw}u,{ch}u,"ladder/{name}","{digest}"}},')
    lines.append("};")
    lines.append(f"static constexpr size_t kLadderCount={len(entries)};")
    LADDER_INC.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return entries


def main():
    global MANIFEST, RUNTIME, GENERATED, FRAME_INC, FROZEN_INC, LADDER_INC
    ap = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--plan", type=Path, help="plan to adopt (default: the runtime plan)")
    ap.add_argument("--model", default="local/vk102",
                    help="model directory to pin (default local/vk102; the small profile is local/small)")
    ap.add_argument("--install", action="store_true",
                    help="copy --plan over port_network_runtime.txt before pinning")
    a = ap.parse_args()

    model = ROOT / a.model
    MANIFEST = model / "manifest"
    RUNTIME = MANIFEST / "port_network_runtime.txt"
    GENERATED = model / "generated"
    FRAME_INC = GENERATED / "port_network_bridge_backend_frame.inc"
    FROZEN_INC = GENERATED / "port_network_bridge_backend_frozen.inc"
    LADDER_INC = GENERATED / "port_network_bridge_backend_ladder.inc"

    source = a.plan or RUNTIME
    if not source.exists():
        raise SystemExit(f"plan not found: {source}")
    if a.install:
        if source.resolve() == RUNTIME.resolve():
            raise SystemExit("--install with --plan pointing at the runtime plan is a no-op")
        shutil.copyfile(source, RUNTIME)
        source = RUNTIME
        print(f"installed {a.plan} -> {RUNTIME}")

    text = source.read_text(encoding="utf-8")
    width, height = port_frame(text)

    # The same two invariants gen_plan enforces, checked again on what we are about to
    # compile in: the port's frame words and its dispatch must describe this extent.
    gp = load_gen_plan()
    problems = gp.verify(width, height, text)
    if problems:
        print(f"refusing to pin {width}x{height}: the plan contradicts itself")
        for p in problems:
            print(f"  {p}")
        return 1

    pixels = width * height
    # The canvas is the dispatch extent, and it is not always the frame: gen_plan pads the
    # short axis up to a 64 multiple (512x288 -> 512x320), and the port planes are sized by
    # the *frame* while the grid walks the canvas. Both numbers are in the plan's first push
    # (words 16/17 = canvas, 20/21 = frame), so read them instead of assuming they match.
    canvas_w, canvas_h = width, height
    for line in text.splitlines():
        if line.startswith("PUSH "):
            w = line.split()
            if len(w) > 21:
                canvas_w, canvas_h = int(w[17]), int(w[18])
            break
    GENERATED.mkdir(parents=True, exist_ok=True)
    FRAME_INC.write_text(
        "// Generated by tools/freeze_plan.py -- do not edit.\n"
        "// The plan on disk decides these; the C++ side must not spell 1280x720 itself.\n"
        f"static constexpr uint32_t kFrameWidth={width},kFrameHeight={height};\n"
        f"static constexpr uint32_t kCanvasWidth={canvas_w},kCanvasHeight={canvas_h};\n"
        "// Floats, not bytes: ioport_images is addressed as float[]. The four ports sit at\n"
        "// kU, kU+20, 2*kU+20 and 2.5*kU+20 with kU = width*height floats (verified against\n"
        "// the 1280x720 plan: 3686400 / 3686420 / 7372820 / 9216020). Only the two offsets\n"
        "// the gather pass needs are named here.\n"
        f"static constexpr uint32_t kFramePixels={pixels}u;\n"
        "static constexpr uint32_t kIoportMotionFloatOffset=8u*kFramePixels+20u;\n"
        "static constexpr uint32_t kIoportDepthFloatOffset=10u*kFramePixels+20u;\n",
        encoding="utf-8", newline="\n")

    if not FROZEN_INC.exists():
        raise SystemExit(f"missing {FROZEN_INC}; run tools/build_assets.py first")
    FROZEN_INC.write_text(rehash(FROZEN_INC.read_text(encoding="utf-8"), RUNTIME),
                          encoding="utf-8", newline="\n")

    print(f"pinned {width}x{height} ({pixels} px) -> {FRAME_INC.name} + {FROZEN_INC.name}")
    print(f"  motion float offset {8 * pixels + 20}, depth float offset {10 * pixels + 20}")

    # The ladder is what lets the backend change scale without a rebuild: it needs the graph
    # (frame/canvas), the file to load and the hash that proves it is the right one.
    try:
        entries = write_ladder(MANIFEST)
    except SystemExit as exc:
        print(f"  ladder: skipped ({exc})")
    else:
        print(f"  ladder: {len(entries)} scales -> {LADDER_INC.name} ("
              + ", ".join(f"{e[0]:.2f}" for e in entries) + ")")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
